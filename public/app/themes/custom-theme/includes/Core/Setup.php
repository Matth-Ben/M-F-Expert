<?php
/**
 * Theme supports, menus, text domain.
 *
 * @package WPGutenberg
 */

namespace WPGutenberg\Core;

/**
 * Core theme setup.
 */
final class Setup {

	/**
	 * Register hooks.
	 *
	 * @return void
	 */
	public function register(): void {
		add_action( 'after_setup_theme', array( $this, 'setup' ) );
		add_filter( 'load_script_translation_file', array( $this, 'script_translation_file' ), 10, 3 );
	}

	/**
	 * JS translations of the theme live in /languages (not wp-content/languages/themes).
	 *
	 * Blocks registered from block.json get their translations loaded automatically by WordPress,
	 * but it looks for `wp-gutenberg-{locale}-{md5}.json` in the global languages folder.
	 * We point it to the same file name in the theme's /languages folder (generated by `pnpm i18n`).
	 *
	 * @param string|false $file   Candidate file.
	 * @param string       $handle Script handle.
	 * @param string       $domain Text domain.
	 * @return string|false
	 */
	public function script_translation_file( $file, string $handle, string $domain ) {
		if ( WPG_TEXT_DOMAIN !== $domain || ! $file || is_file( $file ) ) {
			return $file;
		}

		$theme_file = WPG_DIR . '/languages/' . basename( $file );

		return is_file( $theme_file ) ? $theme_file : $file;
	}

	/**
	 * Declare theme features.
	 *
	 * Design tokens (colors, spacing, layout widths) live in theme.json, not here.
	 *
	 * @return void
	 */
	public function setup(): void {
		load_theme_textdomain( WPG_TEXT_DOMAIN, WPG_DIR . '/languages' );

		add_theme_support( 'title-tag' );
		add_theme_support( 'post-thumbnails' );
		add_theme_support( 'custom-logo', array( 'flex-width' => true, 'flex-height' => true ) );
		add_theme_support( 'responsive-embeds' );
		add_theme_support( 'html5', array( 'search-form', 'gallery', 'caption', 'style', 'script', 'navigation-widgets' ) );

		// Our patterns live in /patterns; core & remote ones are noise for clients.
		remove_theme_support( 'core-block-patterns' );

		register_nav_menus(
			array(
				'main'      => __( 'Main Menu', 'wp-gutenberg' ),
				'secondary' => __( 'Secondary Menu', 'wp-gutenberg' ),
				'footer'    => __( 'Footer Menu', 'wp-gutenberg' ),
				'legals'    => __( 'Legals Menu', 'wp-gutenberg' ),
			)
		);
	}
}
